const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { test, before, after } = require('node:test');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'ecommerce-account-'));
process.env.NODE_ENV = 'test';
process.env.DB_STORAGE = path.join(directory, 'test.sqlite');
process.env.JWT_SECRET = 'account-integration-test-secret-32chars';
const sequelize = require('../src/config/database');
const { User, Pedido, Ticket, NotificacionCorreo } = require('../src/models');
const mail = require('../src/utils/accountMail');
const { app } = require('../server');
const jwt = require('jsonwebtoken');
let server, base, user, other, token;
const originalConfigured = mail.configured;
const originalSend = mail.sendReset;
const deliveries = [];
const headers = (session) => ({ 'Content-Type': 'application/json', ...(session ? { Authorization: `Bearer ${session}` } : {}) });
const request = (url, method = 'GET', body, session) => fetch(base + '/api/auth/' + url, { method, headers: headers(session), ...(body ? { body: JSON.stringify(body) } : {}) });
const login = (email, password) => request('login', 'POST', { email, password });
before(async () => {
  await sequelize.sync({ force: true });
  user = await User.create({ name: 'Ana', apellido: 'Cliente', email: 'ana@example.test', password: 'original123' });
  other = await User.create({ name: 'Otra', apellido: 'Cliente', email: 'otra@example.test', password: 'original123' });
  mail.configured = () => true;
  mail.sendReset = async (email, resetToken) => deliveries.push({ email, token: resetToken });
  server = app.listen(0, '127.0.0.1');
  await new Promise((resolve) => server.once('listening', resolve));
  base = `http://127.0.0.1:${server.address().port}`;
  token = (await (await login(user.email, 'original123')).json()).token;
});
after(async () => {
  mail.configured = originalConfigured; mail.sendReset = originalSend;
  if (server) await new Promise((resolve) => server.close(resolve));
  await sequelize.close(); fs.rmSync(directory, { recursive: true, force: true });
});
test('SCRUM-10 actualiza solo datos permitidos y conserva propiedad de pedidos', async () => {
  const legacy = await Pedido.create({ cliente: user.email, total: 50 });
  const values = { name: ' Ana María ', apellido: ' Nueva ', email: ' NUEVA@example.test ', telefono: '11223344', role: 'admin', password: 'hacked123', id: other.id };
  assert.equal((await request('profile', 'PUT', values)).status, 401);
  assert.equal((await request('profile', 'PUT', { ...values, name: ' ' }, token)).status, 400);
  assert.equal((await request('profile', 'PUT', { ...values, email: 'incorrecto' }, token)).status, 400);
  assert.equal((await request('profile', 'PUT', { ...values, email: other.email.toUpperCase() }, token)).status, 409);
  assert.equal((await request('profile', 'PUT', { ...values, telefono: 'abc' }, token)).status, 400);
  assert.equal((await request('profile', 'PUT', values, token)).status, 200);
  const profile = await (await request('profile', 'GET', null, token)).json();
  assert.equal(profile.user.name, 'Ana María'); assert.equal(profile.user.email, 'nueva@example.test');
  assert.equal(profile.user.telefono, '11223344'); assert.equal(profile.user.password, undefined);
  await user.reload(); assert.equal(user.role, 'client'); assert.ok(await user.comparePassword('original123'));
  assert.equal((await legacy.reload()).cliente, `demo-user:${user.id}:nueva@example.test`);
  assert.equal((await fetch(base + '/api/pedidos', { headers: headers(token) }).then((r) => r.json())).length, 1);
});
