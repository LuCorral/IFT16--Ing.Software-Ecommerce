  mail.configured = () => false;
  assert.equal((await request('forgot-password', 'POST', { email: other.email })).status, 503);
  mail.configured = () => true;
  for (let i = 0; i < 12; i++) await request('forgot-password', 'POST', { email: 'inexistente@example.test' });
  assert.equal((await request('forgot-password', 'POST', { email: 'inexistente@example.test' })).status, 429);
