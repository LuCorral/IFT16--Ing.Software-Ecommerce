test('un administrador nunca recibe los campos de recuperación de otro usuario', async () => {
  const admin = await User.create({ name: 'Admin', apellido: 'Prueba', email: 'admin@example.test', password: 'admin123', role: 'admin' });
  const session = jwt.sign({ id: admin.id, sessionVersion: 0 }, process.env.JWT_SECRET);
  const result = await fetch(base + '/api/usuarios', { headers: headers(session) }).then((r) => r.json());
  assert.ok(result.items.length > 0);
  for (const item of result.items) {
    assert.equal('resetTokenHash' in item, false); assert.equal('resetTokenExpires' in item, false); assert.equal('password' in item, false);
  }
  assert.equal((await request('account', 'DELETE', { password: 'admin123', confirmation: 'ELIMINAR' }, session)).status, 409);
});
test('migración sobre Users existente conserva cuentas y es repetible', async () => {
  const qi = sequelize.getQueryInterface();
  for (const column of ['sessionVersion', 'resetTokenHash', 'resetTokenExpires']) await qi.removeColumn('Users', column);
  const migration = require('../src/migrations/003-account-security');
  await sequelize.transaction(async (transaction) => migration.up(qi, transaction));
  await sequelize.transaction(async (transaction) => migration.up(qi, transaction));
  await other.reload(); assert.equal(other.email, 'otra@example.test'); assert.equal(other.sessionVersion, 0);
});
