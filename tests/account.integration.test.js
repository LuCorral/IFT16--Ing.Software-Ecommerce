test('SCRUM-12 entrega enlace solo a cuentas existentes y valida vencimiento y uso único', async () => {
  assert.equal((await request('forgot-password', 'POST', { email: 'inválido' })).status, 400);
  const unknown = await (await request('forgot-password', 'POST', { email: 'inexistente@example.test' })).json();
  assert.equal(deliveries.length, 0);
  const known = await (await request('forgot-password', 'POST', { email: user.email.toUpperCase() })).json();
  assert.deepEqual(known, unknown); assert.equal(deliveries.length, 1);
  const first = deliveries[0].token;
  await user.reload(); assert.notEqual(user.resetTokenHash, first); assert.ok(user.resetTokenExpires);
  await request('forgot-password', 'POST', { email: user.email });
  const second = deliveries[1].token;
  const body = (resetToken, password = 'recuperada123', confirmPassword = password) => ({ token: resetToken, password, confirmPassword });
  assert.equal((await request('reset-password', 'POST', body(first))).status, 400);
  assert.equal((await request('reset-password', 'POST', body(second, '123'))).status, 400);
  assert.equal((await request('reset-password', 'POST', body(second, 'recuperada123', 'otra'))).status, 400);
  await user.update({ resetTokenExpires: new Date(Date.now() - 1000) });
  assert.equal((await request('reset-password', 'POST', body(second))).status, 400);
  await user.update({ resetTokenExpires: new Date(Date.now() + 60000) });
  const results = await Promise.all([request('reset-password', 'POST', body(second)), request('reset-password', 'POST', body(second))]);
  assert.deepEqual(results.map((r) => r.status).sort(), [200, 400]);
  assert.equal((await request('profile', 'GET', null, token)).status, 401);
  assert.equal((await login(user.email, 'nueva123')).status, 401);
  const response = await login(user.email, 'recuperada123'); assert.equal(response.status, 200);
  token = (await response.json()).token;
  await user.reload(); assert.equal(user.resetTokenHash, null);
});
test('SCRUM-14 cancelar conserva cuenta; confirmar elimina acceso y anonimiza historial', async () => {
  const order = await Pedido.create({ cliente: `demo-user:${user.id}:${user.email}`, total: 10 });
  const ticket = await Ticket.create({ id_pedido: order.id, cliente: 'Ana nueva@example.test', total: 10 });
  await NotificacionCorreo.create({ pedido_id: order.id, destinatario: user.email, asunto: 'Prueba', cuerpo: 'Prueba', estado_pedido: 'Pagado' });
  assert.equal((await request('account', 'DELETE', { password: 'recuperada123', confirmation: 'ELIMINAR' })).status, 401);
  assert.equal((await request('account', 'DELETE', { password: 'recuperada123', confirmation: 'CANCELAR' }, token)).status, 400);
  assert.ok(await User.findByPk(user.id));
  assert.equal((await request('account', 'DELETE', { password: 'incorrecta', confirmation: 'ELIMINAR' }, token)).status, 401);
  assert.equal((await request('account', 'DELETE', { password: 'recuperada123', confirmation: 'ELIMINAR' }, token)).status, 200);
  assert.equal(await User.findByPk(user.id), null);
  assert.equal((await login(user.email, 'recuperada123')).status, 401);
  assert.equal((await request('profile', 'GET', null, token)).status, 401);
  assert.equal((await order.reload()).cliente, `deleted-user:${user.id}`);
  assert.equal((await ticket.reload()).cliente, 'Cuenta eliminada');
  assert.equal(await NotificacionCorreo.count({ where: { pedido_id: order.id } }), 0);
  const replacement = await User.create({ name: 'Nueva', apellido: 'Persona', email: user.email, password: 'otra123' });
  const session = jwt.sign({ id: replacement.id, sessionVersion: 0 }, process.env.JWT_SECRET);
  const orders = await fetch(base + '/api/pedidos', { headers: headers(session) }).then((r) => r.json());
  assert.deepEqual(orders, []);
});
