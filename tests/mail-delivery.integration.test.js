const assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const { test, before, after } = require('node:test');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'mail-delivery-'));
process.env.DB_STORAGE = path.join(directory, 'test.sqlite');
process.env.NODE_ENV = 'test'; process.env.SMTP_HOST = 'smtp.ethereal.email'; process.env.SMTP_FROM = 'tienda@example.test'; process.env.ORDER_MAIL_MODE = 'demo'; process.env.ORDER_MAIL_TO = 'casilla@example.test';
const nodemailer = require('nodemailer');
const original = nodemailer.createTransport;
let sent = [], reject = false;
nodemailer.createTransport = () => ({ sendMail: async (message) => { if (reject) throw Object.assign(new Error('SMTP rechazó'), { code: 'EENVELOPE' }); sent.push(message); return { messageId: message.messageId, accepted: [message.to] }; } });
const db = require('../src/config/database');
const { Pedido, DetallePedido, NotificacionCorreo: Mail } = require('../src/models');
const service = require('../src/utils/notificacionesCorreo');
let order;
before(async () => { await db.sync({ force: true }); order = await Pedido.create({ cliente: 'ana@example.test', total: 20, estado: 'Pendiente' }); await DetallePedido.create({ pedidoId: order.id, productoId: 1, nombreProducto: 'Producto de prueba', cantidad: 2, precioUnitario: 10, subtotal: 20 }); });
after(async () => { nodemailer.createTransport = original; await db.close(); fs.rmSync(directory, { recursive: true, force: true }); });
test('SMTP solo después del commit, con detalle, casilla de prueba y marca demo; rollback no envía', async () => {
  await assert.rejects(db.transaction(async (transaction) => { await service.crearNotificacion({ pedido: order, estado: 'Pendiente', destinatario: 'ana@example.test', transaction }); assert.equal(sent.length, 0); throw new Error('rollback'); }));
  assert.equal(await Mail.count(), 0); assert.equal(sent.length, 0);
  await db.transaction(async (transaction) => { await service.crearNotificacion({ pedido: order, estado: 'Pagado', destinatario: 'ana@example.test', transaction }); assert.equal(sent.length, 0); });
  assert.equal(sent.length, 1); assert.equal(sent[0].to, 'casilla@example.test');
  assert.match(sent[0].text, /Producto de prueba.*2/); assert.match(sent[0].text, /demostración/i); assert.match(sent[0].text, /Fecha/); assert.match(sent[0].text, /Total/);
  assert.equal((await Mail.findOne()).deliveryStatus, 'demo');
});
test('fallo SMTP conserva operación y registro recuperable; reintentos concurrentes no duplican', async () => {
  reject = true;
  let notification;
  await db.transaction(async (transaction) => { await order.update({ estado: 'Enviado' }, { transaction }); notification = await service.crearNotificacion({ pedido: order, estado: 'Enviado', destinatario: 'ana@example.test', transaction }); });
  assert.equal((await order.reload()).estado, 'Enviado');
  assert.equal((await Mail.findByPk(notification.id)).deliveryStatus, 'fallo');
  reject = false;
  await Promise.all([service.deliver(notification.id), service.deliver(notification.id)]);
  assert.equal(sent.length, 2); assert.equal((await Mail.findByPk(notification.id)).attempts, 2);
  await service.deliver(notification.id); assert.equal(sent.length, 2);
});
test('SMTP ambiguo no se reintenta automáticamente y demo rechaza host real', async () => {
  nodemailer.createTransport = () => ({ sendMail: async () => { throw Object.assign(new Error('timeout'), { code: 'ETIMEDOUT' }); } });
  let notification;
  await db.transaction(async (transaction) => { notification = await service.crearNotificacion({ pedido: order, estado: 'Entregado', destinatario: 'ana@example.test', transaction }); });
  assert.equal((await Mail.findByPk(notification.id)).deliveryStatus, 'incierto');
  await service.deliver(notification.id); assert.equal((await Mail.findByPk(notification.id)).attempts, 1);
  nodemailer.createTransport = () => ({ sendMail: async () => { throw Object.assign(new Error('Connection closed unexpectedly after DATA'), { code: 'ECONNECTION' }); } });
  await db.transaction(async (transaction) => { notification = await service.crearNotificacion({ pedido: order, estado: 'Enviado', destinatario: 'ana@example.test', transaction }); });
  assert.equal((await Mail.findByPk(notification.id)).deliveryStatus, 'incierto');
  await service.deliver(notification.id); assert.equal((await Mail.findByPk(notification.id)).attempts, 1);
  process.env.SMTP_HOST = 'smtp.real.example';
  await db.transaction(async (transaction) => { notification = await service.crearNotificacion({ pedido: order, estado: 'Cancelado', destinatario: 'ana@example.test', transaction }); });
  assert.equal((await Mail.findByPk(notification.id)).deliveryStatus, 'fallo');
});
