test('fallo al registrar reintegro revierte cancelación, stock y saldo; permite reintento', async () => {
  await client.update({ corporateBalanceCents: 400 });
  const order = (await (await checkout()).json()).pedido;
  const stock = (await product.reload()).stock;
  const create = Movement.create;
  Movement.create = async () => { throw new Error('fallo deliberado de reintegro'); };
  try { assert.equal((await request(`/api/pedidos/${order.id}/cancelar`, 'PATCH')).status, 500); }
  finally { Movement.create = create; }
  assert.equal((await Pedido.findByPk(order.id)).estado, 'Pendiente');
  assert.equal((await product.reload()).stock, stock); assert.equal(Number((await client.reload()).corporateBalanceCents), 0);
  assert.equal((await request(`/api/pedidos/${order.id}/cancelar`, 'PATCH')).status, 200);
  assert.equal(Number((await client.reload()).corporateBalanceCents), 400);
});
test('recepción de canje completo usa el estado final Pagado y reintentos no duplican correos', async () => {
  await client.update({ corporateBalanceCents: 1000 });
  const key = randomUUID();
  const responses = await Promise.all([checkout(key), checkout(key)]);
  const data = await Promise.all(responses.map((r) => r.json()));
  const created = data.find((r) => r.correo_simulado);
  assert.equal(created.pedido.estado, 'Pagado');
  assert.match(created.correo_simulado.asunto, /Recibimos tu pedido/);
  assert.equal(created.correo_simulado.estado_pedido, 'Pagado');
  assert.match(created.correo_simulado.cuerpo, /Estado: Pagado/);
  assert.doesNotMatch(created.correo_simulado.cuerpo, /Pendiente/);
  assert.equal((await Pedido.findByPk(created.pedido.id)).estado, 'Pagado');
  const rows = await Mail.findAll({ where: { pedido_id: created.pedido.id } });
  assert.equal(rows.length, 2); assert.equal(rows.filter((r) => /Recibimos/.test(r.asunto)).length, 1); assert.equal(rows.filter((r) => /Pago confirmado/.test(r.asunto)).length, 1);
  assert.equal((await request(`/api/pedidos/${created.pedido.id}/pagar`, 'POST', { metodo: 'tarjeta' })).status, 200);
  assert.equal(await Mail.count({ where: { pedido_id: created.pedido.id } }), 2);
});
test('recepción mixta queda Pendiente; rechazo no confirma y aprobación repetida confirma Pagado una vez', async () => {
  await client.update({ corporateBalanceCents: 400 });
  const key = randomUUID();
  const created = await (await checkout(key)).json();
  assert.equal(created.pedido.estado, 'Pendiente'); assert.equal(created.correo_simulado.estado_pedido, 'Pendiente');
  assert.match(created.correo_simulado.cuerpo, /Estado: Pendiente/);
  assert.equal((await checkout(key)).status, 200);
  const pay = (resultadoSimulado = 'aprobado') => request(`/api/pedidos/${created.pedido.id}/pagar`, 'POST', { metodo: 'transferencia', resultadoSimulado });
  const rejected = await (await pay('rechazado')).json();
  assert.equal(rejected.pago.estado, 'Rechazado'); assert.equal(rejected.estadoPedido, 'Pendiente');
  assert.equal(await Mail.count({ where: { pedido_id: created.pedido.id } }), 1);
  const approved = await Promise.all([pay(), pay()]);
  const results = await Promise.all(approved.map((r) => r.json()));
  const confirmation = results.find((r) => r.correo_simulado)?.correo_simulado;
  assert.equal(confirmation.estado_pedido, 'Pagado'); assert.match(confirmation.cuerpo, /Estado: Pagado/);
  assert.equal(await Mail.count({ where: { pedido_id: created.pedido.id } }), 2);
});
