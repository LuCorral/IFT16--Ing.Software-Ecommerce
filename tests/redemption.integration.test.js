test('validaciones, stock y fallo del movimiento no consumen saldo ni dejan pedido', async () => {
  await client.update({ corporateBalanceCents: 1000 });
  assert.equal((await checkout(undefined, null)).status, 401);
  assert.equal((await checkout(undefined, admin)).status, 403);
  assert.equal((await checkout(undefined, other)).status, 409);
  assert.equal((await checkout(undefined, client, { requestId: 'invalid' })).status, 400);
  assert.equal((await checkout(undefined, client, { useCredit: 'true' })).status, 400);
  const before = await Pedido.count(), stock = (await product.reload()).stock;
  const create = Movement.create; Movement.create = async () => { throw new Error('fallo deliberado'); };
  try { assert.equal((await checkout()).status, 500); } finally { Movement.create = create; }
  assert.equal(await Pedido.count(), before); assert.equal((await product.reload()).stock, stock);
  assert.equal(Number((await client.reload()).corporateBalanceCents), 1000);
  assert.equal((await checkout(undefined, client, { productos: [{ productoId: product.id, cantidad: 999 }] })).status, 400);
});
